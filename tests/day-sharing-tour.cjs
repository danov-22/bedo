 const touch=await page.context().newCDPSession(page);fab=await page.locator('#bd-fab').boundingBox();
 for(const expected of ['block','note']){
   await touch.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:fab.x+40,y:fab.y+30}]});
   await touch.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:fab.x+10,y:fab.y+30}]});
   await touch.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
   assert.equal(await page.locator('#bd-fab').getAttribute('data-mode'),expected,'finger swipe switches action');
 }
 await page.locator('#bd-fab').click();await page.locator('#bd-note-form').waitFor();await page.locator('[data-action=close]').click();
